//! The map from the menu to SCPI: for every menu `Item` that has a header of its own, that header, in ONE table. The
//! tests (`scpi_coverage_tests.rs`) walk it both ways (a press in the menu is seen by the query, a set by SCPI is
//! shown by the menu item) and check the "Menu equivalent" column of `docs/scpi/*.md` against it, so the reference
//! cannot say one thing and the code another. The text of the column for a row of the table is `<group> > <label>`:
//! the group is the menu it belongs to as the table names it, the label is what the menu item shows.
//!
//! `header` is as the reference writes it (`<n>` is a number, `[...]` is optional): the test sends it with 1 for `<n>`
//! and without the brackets. A row that needs a state of its own (a trigger type, a decoder) has a `pre` to set it up.
use super::*;

/// One row of the map.
pub(super) struct Row {
    pub header: &'static str,
    /// the leading argument of the commands that take a slot (`REFerence:VSCale 1,0.5`, `REFerence:VSCale? 1`), else empty
    pub index: &'static str,
    pub item: Item,
    pub group: &'static str,
    pub pre: fn(&mut Ui),
}

fn none(_: &mut Ui) {}

fn r(header: &'static str, item: Item, group: &'static str) -> Row { Row { header, index: "", item, group, pre: none } }
fn ri(header: &'static str, index: &'static str, item: Item, group: &'static str) -> Row { Row { header, index, item, group, pre: none } }
fn p(header: &'static str, item: Item, group: &'static str, pre: fn(&mut Ui)) -> Row { Row { header, index: "", item, group, pre } }

fn trig(t: TrigType, u: &mut Ui) { u.set_trig_type(t); }
fn spectrum_on(u: &mut Ui) { u.m.view = AView::Spectrum; }
fn eye_on(u: &mut Ui) { u.m.view = AView::Eye; }
fn uart(u: &mut Ui) { u.m.dec_on = true; u.m.dec_proto = Proto::Uart; }
fn spi(u: &mut Ui) { u.m.dec_on = true; u.m.dec_proto = Proto::Spi; }
fn can(u: &mut Ui) { u.m.dec_on = true; u.m.dec_proto = Proto::Can; }
fn ch2(u: &mut Ui) { u.m.ch[1].on = true; }
fn fast_timebase(u: &mut Ui) {
    for i in 0..tscales().len() {
        u.m.tscale = i;
        u.m.tfine = 1.0;
        if u.m.time_per_div() <= 1e-6 { break; }
    }
}

